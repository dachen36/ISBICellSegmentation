import cv2
import numpy as np

# 读取你的标签图
mask = cv2.imread('masks/1.png', 0)

# 打印图像中的最大值
print(f"图像的最大像素值是: {mask.max()}")
print(f"图像的最小像素值是: {mask.min()}")

# “在项目初期，我发现模型 Loss 一直卡在 $0.24$ 左右无法下降。经过排查，我发现是因为 Label 图像素值为 0-255，而模型输出在 $0-1$ 之间，巨大的数值差异导致梯度计算异常。我通过在 Dataset 类中对 Mask 进行**二值化归一化处理（除以 255 并取阈值）**解决了这个问题。修改后，Loss 顺利下降到了 $0.05$ 以下，分割边缘也变得更加清晰。”